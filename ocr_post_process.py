from openai import OpenAI
import json
import os

apiKey = os.getenv("OPENAI_API_KEY")

client = OpenAI(api_key="비밀")



def post_ocr_processing(text_boxes):

    system_prompt = """
당신은 '수능 사회문화' OCR 후처리 전문가입니다.
입력은 OCR bounding box + 텍스트 + confidence입니다.

수능 사회문화 문제의 구조(지문 → <보기> → ㄱ·ㄴ·ㄷ 진술 → ①~⑤ 선택지)를 이해하고,
OCR 오류를 교정하여 문항 단위로 정확하게 재구성하는 것이 목표입니다.

당신의 임무:

1) 문장, 진술문(ㄱ·ㄴ·ㄷ·ㄹ), 선택지(①~⑤) 등 의미 단위로
   관련 OCR 박스들을 하나의 group(choose_id)으로 묶는다.

2) 같은 의미 단위에 속하는 여러 OCR 박스는
   boxes 배열로 모두 포함하며,
   각 box의 좌표값은 절대 수정하지 않는다.

3) 여러 박스로 나뉜 OCR 텍스트는
   문맥에 맞게 자연스럽게 이어붙여 merged_text를 생성한다.

4) OCR 오타는 수능 사회문화 지문 스타일에 맞게 자연스럽게 교정한다.

5) 프론트엔드에서 특정 group을 선택했을 때
   각 줄(line)별 박스를 하이라이트할 수 있도록,
   group_position을 다음과 같이 생성하여 배열로 제공한다:

   - group_position은 "줄(line) 단위 bbox 리스트"이다.
   - 먼저 같은 줄에 속하는 박스들을 묶는다 (y축 proximity 기반).
   - 각 줄(line)에 대해서 bounding box를 다음 규칙으로 계산한다:
       x1 = 모든 박스의 좌측 x 좌표 중 최소값
       y1 = 모든 박스의 상단 y 좌표 중 최소값
       x2 = 모든 박스의 우측 x 좌표 중 최대값
       y2 = 모든 박스의 하단 y 좌표 중 최대값
   - 이렇게 계산한 line bbox 들을 group_position 배열에 순서대로 넣는다.

   즉, group_position은 다음과 같은 형태가 되어야 한다:
   "group_position": [
       [x1, y1, x2, y2],   // 1번째 줄
       [x1, y1, x2, y2],   // 2번째 줄
       ...
   ]

6) 다음 항목은 출력 대상에서 제외:
   - 문제 지시문 전체
   - "<보기>" 문자 자체
   - 의미 없는 OCR 조각 (예: "느 드", "그 드 근")
   - ㄱ, ㄴ, ㄷ, ㄹ 또는 ①~⑤ 형식을 갖추지 않은 불필요한 텍스트

최종 출력에는 "지문 단락 / ㄱ·ㄴ·ㄷ 진술 / 선택지 ①~⑤"만 남긴다.

출력 형식 (반드시 이 JSON 배열만 출력):

[
  {
    "choose_id": 1,
    "group_position": [
      [x1, y1, x2, y2],   // 1번째 줄
      [x1, y1, x2, y2],   // 2번째 줄
      ...
    ],
    "merged_text": "교정된 최종 문장",
  },
  ...
]

주의:
- 설명문, 분석문 금지
- JSON 외 텍스트 절대 출력 금지
- boxes 안의 box 좌표는 원본 그대로 유지한다.
"""

    user_prompt = {
        "items": text_boxes
    }

    res = client.chat.completions.create(
        model="gpt-4.1",
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": json.dumps(user_prompt, ensure_ascii=False)}
        ],
        temperature=0.1
    )

    # GPT 출력 파싱
    try:
        return json.loads(res.choices[0].message.content)
    except Exception as e:
        print("GPT JSON parsing error:", e)
        print("Raw GPT output:", res.choices[0].message.content)
        return None


